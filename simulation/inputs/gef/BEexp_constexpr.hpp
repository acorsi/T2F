inline constexpr BEArray BEexp = MakeBEexp();
inline double GetBEexpRaw(int Z, int A)
{
    const int N = A - Z;

    if (Z < 0 || Z >= 137 || N < 0 || N >= 204)
        return 0.0;

    return BEexp[N][Z];   // si ton tableau est bien BEexp[N][Z]
}
inline double GetBEexp(int Z, int A)
{
    const int N = A - Z;
    if (Z < 0 || Z >= BE_ZMAX || N < 0 || N >= BE_NMAX)
        throw std::out_of_range("BEexp: invalid Z,A");

    const double be = BEexp[N][Z];

  if (be <= BE_MISSING / 10.0)
    std::cout << "   =>missing mass for Z=" << std::to_string(Z) << " A=" << std::to_string(A) << " : event thrown." << std::endl ;
  
    //    throw std::runtime_error("BEexp: missing mass for Z=" +
    //			     std::to_string(Z) + " A=" + std::to_string(A));
  
  return be;
}
double GetBEexpSafe(int Z, int A)
{
    int N = A - Z;

    double be = GetBEexpRaw(Z, A);

    if (be != BE_MISSING)
        return be;

    double be_minus = GetBEexp(Z, A - 1);
    double be_plus  = GetBEexp(Z, A + 1);

    if (be_minus > BE_MISSING/10. && be_plus > BE_MISSING/10)
        return 0.5 * (be_minus + be_plus);
    else
      return BE_MISSING; //Ajout LG 18 Nov 2026 pour reconnaitre les cas où la masse n'est pas connue sans arrêt du prog.
    
    throw std::runtime_error(
        "BEexp: missing mass for Z=" + std::to_string(Z) +
        " A=" + std::to_string(A)
    );
}
inline double GetNuclearMassMeV_fromBE(int Z, int A)
{
    constexpr double mp = 938.27208816; // MeV/c2
    constexpr double mn = 939.56542052; // MeV/c2
    const int N = A - Z;
    return Z * mp + N * mn + GetBEexpSafe(Z, A);
}

